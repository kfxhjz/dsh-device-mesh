// ---------------------------------------------------------------------------
// Sandboxed apply() smoke test
// ---------------------------------------------------------------------------
//
// The bundle is meant for a browser, but `apply` itself only needs the Cordis
// context. Executing the factory in a `node:vm` sandbox with a stubbed `react`
// and a recording context proves the registration graph (ids, locale namespace,
// injected capabilities) without launching a browser.

interface SlotRegistration {
  readonly options: Record<string, unknown>
  readonly component: unknown
}

interface SandboxModule {
  readonly inject: readonly string[]
  readonly apply: (ctx: unknown) => void
}

/** Run `client.js` in an isolated context and return the plugin exports. */
function evaluateInSandbox(): SandboxModule {
  const source = bundle()
  let factory: ((requireModule: (id: string) => unknown) => unknown) | null = null
  const sandbox = {
    window: {
      __ModuleLoader__: {
        load: (entry: { readonly id: string; readonly factory: (requireModule: (id: string) => unknown) => unknown }) => {
          factory = entry.factory
        },
      },
    },
    console,
    TextEncoder,
    TextDecoder,
    setTimeout,
    clearTimeout,
    setInterval,
    clearInterval,
  }
  vm.runInNewContext(source, sandbox, { filename: 'client.js' })
  // The assignment happens inside the sandbox callback, so the declared
  // variable's control-flow type stays `null` here; assert on a cast copy.
  const resolvedFactory = factory as unknown as
    | ((requireModule: (id: string) => unknown) => unknown)
    | null
  assert.equal(typeof resolvedFactory, 'function', 'window.__ModuleLoader__.load must register a factory')
  const reactStub = {
    createElement: () => null,
    useState: (initial: unknown) => [typeof initial === 'function' ? (initial as () => unknown)() : initial, () => {}],
    useEffect: () => {},
    useRef: (initial: unknown) => ({ current: initial }),
    useMemo: (factoryFn: () => unknown) => factoryFn(),
    useCallback: (callback: (...args: unknown[]) => unknown) => callback,
  }
  const loaded = (resolvedFactory as (requireModule: (id: string) => unknown) => unknown)((id: string) => {
    if (id === 'react') return reactStub
    throw new Error(`unexpected baseline module requested by the plugin: ${id}`)
  }) as SandboxModule
  return loaded
}

test('module factory and apply() register the documented slot graph', async () => {
  const plugin = evaluateInSandbox()
  assert.deepEqual([...plugin.inject], ['slots', 'locale', 'layout'])

  const registrations: SlotRegistration[] = []
  const injected: string[] = []
  const localeCalls: { namespace: string; dictionaries: Record<string, Record<string, string>> }[] = []
  const selectedPanels: string[] = []
  const openedTabs: { kind: string; options: unknown }[] = []
  const sidebarRight = {
    openTab: (kind: string, options?: unknown) => { openedTabs.push({ kind, options }) },
  }
  const ctx = {
    slots: {
      inject: (name: string, callback: () => unknown): (() => void) => {
        injected.push(name)
        callback()
        return () => {}
      },
      register: (options: Record<string, unknown>, component: unknown): (() => void) => {
        registrations.push({ options, component })
        return () => {}
      },
    },
    locale: {
      register: (namespace: string, dictionaries: Record<string, Record<string, string>>): (() => void) => {
        localeCalls.push({ namespace, dictionaries })
        return () => {}
      },
      bind: (namespace: string) => (key: string) => `[${namespace}]${key}`,
    },
    layout: {
      selectPanel: (panelId: string) => { selectedPanels.push(panelId) },
    },
    effect: (callback: () => void | (() => void)): void => { callback() },
    get: (name: string): unknown => (name === 'sidebarRight' ? sidebarRight : undefined),
  }

  plugin.apply(ctx)

  assert.deepEqual(injected, ['main', 'sidebar.panellist', 'shell.overlay'])
  assert.equal(localeCalls.length, 1)
  const locale = localeCalls[0]
  assert.ok(locale !== undefined)
  assert.equal(locale.namespace, 'deviceMesh')
  assert.equal(locale.dictionaries.zh?.panel, '远程设备')
  assert.equal(locale.dictionaries.en?.panel, 'Devices')
  assert.deepEqual(
    Object.keys(locale.dictionaries.zh ?? {}).sort(),
    Object.keys(locale.dictionaries.en ?? {}).sort(),
    'zh and en dictionaries must cover the same keys',
  )

  const byName = new Map(registrations.map(entry => [String(entry.options.name), entry]))
  assert.equal(registrations.length, 3)
  const main = byName.get('main')
  assert.ok(main !== undefined)
  assert.equal(main.options.key, 'device-mesh')
  assert.equal(main.options.locale, 'deviceMesh')
  assert.equal(typeof main.component, 'function')

  const panelList = byName.get('sidebar.panellist')
  assert.ok(panelList !== undefined)
  assert.equal(panelList.options.id, 'device-mesh')
  assert.equal(panelList.options.order, 40)
  const label = panelList.options.label as () => string
  assert.equal(label(), '[deviceMesh]panel')

  const overlay = byName.get('shell.overlay')
  assert.ok(overlay !== undefined)
  assert.equal(overlay.options.id, 'device-mesh.pending')

  // The optional right-sidebar capability is injected as a callback, not ctx.
  const mainFace = (main.options.inject as () => Record<string, unknown>)()
  const openRemoteTab = mainFace.openRemoteTab as (url: string) => boolean | Promise<boolean>
  assert.equal(await openRemoteTab('http://127.0.0.1:1234/?token=x'), true)
  assert.equal(openedTabs.length, 1)
  assert.equal(openedTabs[0]?.kind, 'browser')
  const options = openedTabs[0]?.options as { params?: { url?: string } } | undefined
  assert.equal(options?.params?.url, 'http://127.0.0.1:1234/?token=x')
})

