test('only baseline platform modules are required (React external, qrcode inlined)', () => {
  const source = bundle()
  const required = new Set<string>()
  for (const match of source.matchAll(/\brequire\((["'])([^"']+)\1\)/gu)) {
    const id = match[2]
    if (id !== undefined) required.add(id)
  }
  for (const id of required) {
    assert.ok(BASELINE_EXTERNALS.has(id), `non-baseline module required from the platform table: ${id}`)
  }
  assert.ok(required.has('react'), 'React must stay external (a second React copy breaks hooks)')
  assert.ok(!required.has('qrcode-generator'), 'qrcode-generator must be inlined into the bundle')
  assert.match(source, /node_modules\/qrcode-generator\/dist\/qrcode\.mjs/u)
  assert.ok(!required.has('react-dom'), 'the plugin must not create its own React root')
})

