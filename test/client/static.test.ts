/**
 * Static contract checks for the dsh-device-mesh browser bundle.
 *
 * This test never opens a browser: it validates the built `client.js` artifact
 * against the DSH client-module contract (docs/development.md §4) and
 * against the UI/API surface this package promises. When the bundle is absent
 * the test builds it first, so the suite is green from a clean checkout.
 */
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const bundlePath = join(root, 'client.js')
const packageJson = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { name: string }

/** Modules the DSH web shell provides; the bundle must never inline them. */
const BASELINE_EXTERNALS = new Set([
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  'zod',
  '@tanstack/react-virtual',
  'dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
])

let cached: string | null = null

/** Read the bundle, building it once when a clean checkout has no artifact. */
function bundle(): string {
  if (cached !== null) return cached
  if (!existsSync(bundlePath)) {
    const built = spawnSync(process.execPath, [join(root, 'scripts', 'build.mjs'), '--client'], {
      cwd: root,
      encoding: 'utf8',
    })
    assert.equal(built.status, 0, `client build failed\nstdout: ${built.stdout}\nstderr: ${built.stderr}`)
  }
  assert.ok(existsSync(bundlePath), 'client.js must exist after the client build')
  cached = readFileSync(bundlePath, 'utf8')
  return cached
}

test('client bundle exists, parses, and is non-trivial in size', () => {
  const source = bundle()
  const bytes = statSync(bundlePath).size
  assert.ok(bytes > 60_000, `bundle is suspiciously small (${bytes} bytes)`)
  assert.ok(bytes < 1_500_000, `bundle is suspiciously large (${bytes} bytes)`)
  const check = spawnSync(process.execPath, ['--check', bundlePath], { encoding: 'utf8' })
  assert.equal(check.status, 0, `node --check failed: ${check.stderr}`)
  assert.match(source, /window\.__ModuleLoader__\.load\(\{/u)
})

test('bundle follows the lazy-CJS module-loader wrapper contract', () => {
  const source = bundle()
  // The banner advertises the artifact as generated; the wrapper itself starts
  // the first non-comment statement.
  assert.match(source, /^\/\/ Generated by scripts\/build\.mjs from src\/client/u)
  const firstCode = source
    .split('\n')
    .filter(line => !line.trimStart().startsWith('//'))
    .join('\n')
    .trimStart()
  assert.ok(firstCode.startsWith('window.__ModuleLoader__.load({'), 'the loader call must be the first statement')
  assert.match(source, /id: "dsh-device-mesh"/u)
  assert.match(source, /factory: \(require\) =>/u)
  assert.match(source, /return module\.exports/u)
  assert.match(source, /\}\)\s*$/u)
})

