#!/usr/bin/env node
/**
 * Build script for dsh-device-mesh.
 *
 * Produces two artifacts from TypeScript sources:
 *   - `lib/host/index.js` — the Node-side Cordis plugin (bundled ESM; `ws` and
 *     node builtins stay external so the profile's node_modules resolve them).
 *   - `client.js` — the browser half, wrapped in the DSH client module-loader
 *     contract (`window.__ModuleLoader__.load({ id, factory })`).
 *
 * The wrapper format and the external baseline list are documented in
 * docs/development.md §4. Do not change them without re-reading that
 * section: React must stay external (a second React copy breaks hooks) and the
 * module id must equal the package name.
 */
import { build, context } from 'esbuild'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const packageName = pkg.name

/** Modules the DSH web shell provides; they must never be bundled. */
const CLIENT_EXTERNALS = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  'zod',
  '@tanstack/react-virtual',
  'dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

const args = new Set(process.argv.slice(2))
const watch = args.has('--watch')
const onlyHost = args.has('--host')
const onlyClient = args.has('--client')

/** @type {import('esbuild').BuildOptions} */
const hostOptions = {
  entryPoints: [join(root, 'src/host/index.ts')],
  outfile: join(root, 'lib/host/index.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  sourcemap: false,
  packages: 'external',
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
}

/** @type {import('esbuild').BuildOptions} */
const clientOptions = {
  entryPoints: [join(root, 'src/client/index.tsx')],
  outfile: join(root, 'client.js'),
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  external: CLIENT_EXTERNALS,
  sourcemap: false,
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: {
    js: `// Generated by scripts/build.mjs from src/client — do not edit by hand.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(packageName)},\n  factory: (require) => {\n    const module = { exports: {} };\n    const exports = module.exports;`,
  },
  footer: {
    js: 'return module.exports\n  },\n})',
  },
}

async function run() {
  const jobs = []
  if (!onlyClient) jobs.push(['host', hostOptions])
  if (!onlyHost) jobs.push(['client', clientOptions])

  for (const [label, options] of jobs) {
    if (watch) {
      const ctx = await context(options)
      await ctx.watch()
      console.log(`[build] watching ${label}`)
    } else {
      await build(options)
      console.log(`[build] built ${label}`)
    }
  }
}

await run()
